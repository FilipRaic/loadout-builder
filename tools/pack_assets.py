"""Write the asset manifest and the embedded-image fallback.

js/manifest.js  Small. Item list, medians, pattern list and relative image paths. The
                website loads only this; the images download in parallel as normal files.
js/assets.js    Large. Every image as a data URI, keyed by its path. Browsers refuse to
                feed local image files into WebGL when index.html is opened straight from
                disk (file://), so app.js loads this file only in that case.

Run after changing anything in assets/:   python tools/pack_assets.py
"""

import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "assets")
HEADER = "// Generated by tools/pack_assets.py - do not edit by hand.\n"


def uri(path):
    ext = os.path.splitext(path)[1].lower()
    mime = {
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".png": "image/png",
        ".webp": "image/webp",
    }[ext]
    with open(path, "rb") as f:
        return f"data:{mime};base64," + base64.b64encode(f.read()).decode()


embedded = {}


def rel(path):
    """Path relative to the site root, with forward slashes; also embeds the file."""
    r = os.path.relpath(path, ROOT).replace(os.sep, "/")
    embedded[r] = uri(path)
    return r


with open(os.path.join(A, "meta.json")) as f:
    meta = json.load(f)
angles = []
for i, ang in enumerate(meta["angles"]):
    d = os.path.join(A, f"angle{i}")
    angles.append(
        {
            "medians": ang["medians"],
            "base": rel(os.path.join(d, "base.jpg")),
            "shade": rel(os.path.join(d, "shade.png")),
            "masks": [
                rel(os.path.join(d, f))
                for f in sorted(os.listdir(d))
                if f.startswith("mask")
            ],
        }
    )
patterns = []
with open(os.path.join(A, "patterns", "patterns.json")) as f:
    pattern_entries = json.load(f)
for p in pattern_entries:
    fn = next(
        f
        for f in os.listdir(os.path.join(A, "patterns"))
        if os.path.splitext(f)[0] == p["id"] and not f.endswith(".json")
    )
    patterns.append({**p, "src": rel(os.path.join(A, "patterns", fn))})

out = {
    "items": meta["items"],
    "tint": meta.get("tint", [1, 1, 1]),
    "width": meta["width"],
    "height": meta["height"],
    "angles": angles,
    "patterns": patterns,
}
for name, var, data in (
    ("manifest.js", "LOADOUT_ASSETS", json.dumps(out, indent=2)),
    ("assets.js", "LOADOUT_EMBEDDED", json.dumps(embedded)),
):
    path = os.path.join(ROOT, "js", name)
    with open(path, "w", newline="\n") as f:
        f.write(HEADER)
        f.write(f"window.{var} = {data};\n")
    print("wrote js/" + name, round(os.path.getsize(path) / 1e3, 1), "kB")
